function facilityList( ids, is_preview ){								
								
	var ret = [];							
								
	ids.forEach(function(id){							
								
		var sc = facilityData(id);						
								
		if (!sc) return;						
		if (!sc.is_publish && !is_preview) return;		
		
		var Body = document.getElementById('body'); 
		var imageSource = Body.getAttribute('data-tmpdir') + 'assets/image/facility/thumbs/';
								
		var specs = [];						
								
		if(sc["spec"]){						
			sc["spec"].forEach(function(spec){					
				specs.push('<li class="bg-orange2 txt-medium">' + spec + '</li>');				
			});					
		}						
								
		if( specs.length ){						
			specs.unshift('<ul class="facility-list__tag flex flex-wrap">');					
			specs.push('</ul>');					
		}						
								
		ret.push('<div class="facility-list-childs">');
		ret.push('<p class="photo mb-half"><a href="' + sc["url"] + '" target="' + sc["target"] + '"><img src="' + imageSource + id + '.webp" alt="' + sc["name"] + '"/></a></p>');
					
						
		ret.push('<p class="facility-list__service">' + sc["service"] + '</p>');


		var opens = [];

		if(sc["open"]){										
				ret.push('<span class="facility-open">' + sc["open"] + '</span>');						
		}

		ret.push('<h3 class="facility-list__ttl txt-bold"><a href="' + sc["url"] + '" target="' + sc["target"] + '">' + sc["name"] + '</a></h3>');						
		ret.push('<p class="facility-list__address">' + sc["address"] + '</p>');						
		ret.push( specs.join("\n") );					
		ret.push('</div>');						
								
	});							
								
	return ret.join("\n");							
								
}								
								
function include(s){								
	document.write(s);							
}								
								
function filterGroup( area_id, is_preview ){								
	return Object.values( facilityData() ).filter(function(db){							
		if (!db.is_publish && !is_preview) return;						
		return db.area_group == area_id;						
	});							
}								
								
function filterSpec( search_str ){								
	return Object.values( facilityData() ).filter(function(db){							
		if (!db.spec) return false;						
		return db.spec.indexOf(search_str) > -1;						
	});							
}								
								

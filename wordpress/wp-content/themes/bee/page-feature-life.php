    <hr>
    <h4>●寝る前に飲むのは「宝の水」</h4>
    <p>就寝前の水分補給も大切。寝ている間に失われる水分をあらかじめ補給しておくことで体への負担か軽減されます。この時、気をつけたいのは糖分の入ったジュースはやめておくこと。血糖値が上がり、よけいに血液の粘性を高めてしまいます。</p>
    <hr>
    <h4>●日中は少しずつ1.2リットル以上を飲む</h4>
    <p>「早めに、こまめに」というのが、理想的な水の飲み方。「のどか渇いた」と感じてから飲むのではなく、渇きを感じる前に水分をとることが重要です。ビールなどのアルコールや多量のカフェインを含む飲料は、尿の量を増やすので水分補給には適しません。</p>

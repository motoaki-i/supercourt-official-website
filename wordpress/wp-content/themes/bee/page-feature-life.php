  <h3>水にこだわれば体がよろこぶ</h3>
  <p>人間の体は60～70%が水分。水の働きによって代謝が促進されたり体温の調節が行われ、生命の機能が保たれています。水の不足による健康への害は大きく、脱水症状や消化不良といった日常の不調から、脳梗塞や心筋梗塞など重篤な症状につながる場合も。逆にいえば、質の良い水をまめに補給することは、最も簡単な健康管理だといえるでしょう。</p>
  <h3>効果的な水の飲み方</h3>
  <p>人間の体からは、汗や尿の形で1日に約2.4リットル水分が失われます。もちろん個人差はありますが、毎日、出て行く以上の水分を補給することが必要。食事から取り入れる水分は約1リットル、体内の代謝によってつくられる水分が約0.3リットルといわれるので、少なくとも1.2リットルは、意識的に水を飲むようにしたいもの。「そんなに飲めない!」と思いますか?大丈夫、一度にたくさん飲むのではなく、何回もに分けて少しずつ…から始めてみましょう。</p>
